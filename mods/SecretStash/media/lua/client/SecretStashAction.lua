function DigSecretStash() 
local pl = getPlayer() 
local sq = getCell():getGridSquare(pl:getX(), pl:getY(), pl:getZ());
local shelf = IsoThumpable.new(getCell(), sq, "floors_overlay_street_01_"..ZombRand(32), false, 
ISSimpleFurniture:new("shelves", "overlay_grime_floor_01_"..ZombRand(13,16), "floors_overlay_tiles_02_"..ZombRand(9,16)));
shelf:setIsContainer(true);
shelf:setCanPassThrough(true);
shelf:setIsDismantable(true);
shelf:setCanBeLockByPadlock(true);
shelf:getContainer():setType("crate");
if sq:isOutside() then
shelf:getContainer():AddItems("Base.Plank", ZombRand(2));
else
shelf:getContainer():AddItems("Base.Stone", ZombRand(2));
end
sq:AddTileObject(shelf);
if isClient() then 
shelf:transmitCompleteItemToServer(); 
end
triggerEvent("OnObjectAdded", shelf) 
ISInventoryPage.renderDirty = true;
ISInventoryPage.dirtyUI();

local ps=pl:getStats();
    ps:setHunger(0.01+ps:getHunger()*1.2);
    ps:setFatigue(0.01+ps:getFatigue()*1.2);
	ps:setThirst(0.01+ps:getThirst()*1.2);
	
	if sq:isOutside() then
getSoundManager():PlayWorldSound("DropSoilFromDirtBag", sq, 0, 5, 1, false); 
addSound(pl, pl:getX(), pl:getY(), pl:getZ(), 5, 1);
else
getSoundManager():PlayWorldSound("LogAddToStack", sq, 0, 5, 1, false); 
addSound(pl, pl:getX(), pl:getY(), pl:getZ(), 5, 1);
end
end
