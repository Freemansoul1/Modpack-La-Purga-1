require "lua_timers"

ZAV = ZAV or {}

local function doZombificationDiceRoll()
    return ZombRand(100) < SandboxVars.ZombieAttackVariety.chanceOfZombification - 1;
end

local function doFakeInfectionDiceRoll()
    return ZombRand(100) < SandboxVars.ZombieAttackVariety.chanceOfFakeInfection - 1;
end

ZAV.tryDoPartInfection = function(part)
    if doFakeInfectionDiceRoll() then
        print("ZAV: DO FAKE INFECTION")
        part:SetFakeInfected(true);
    elseif doZombificationDiceRoll() then
        print("ZAV: DO REAL INFECTION")
        part:SetFakeInfected(false);
        part:SetInfected(true);
        part:setInfectedWound(true);
    end
end

ZAV.getBodyDamage = function()
    local player = getPlayer();
    local bodyDamage = player:getBodyDamage();
    return {
        bodyDamage = bodyDamage,
        parts = {bodyDamage:getBodyPart(BodyPartType.Torso_Upper), bodyDamage:getBodyPart(BodyPartType.Torso_Lower),
                 bodyDamage:getBodyPart(BodyPartType.ForeArm_L), bodyDamage:getBodyPart(BodyPartType.ForeArm_R),
                 bodyDamage:getBodyPart(BodyPartType.UpperArm_L), bodyDamage:getBodyPart(BodyPartType.UpperArm_R),
                 bodyDamage:getBodyPart(BodyPartType.Groin), bodyDamage:getBodyPart(BodyPartType.Neck),
                 bodyDamage:getBodyPart(BodyPartType.Back), bodyDamage:getBodyPart(BodyPartType.Head),
                 bodyDamage:getBodyPart(BodyPartType.UpperLeg_L), bodyDamage:getBodyPart(BodyPartType.UpperLeg_R),
                 bodyDamage:getBodyPart(BodyPartType.LowerLeg_L), bodyDamage:getBodyPart(BodyPartType.LowerLeg_R),
                 bodyDamage:getBodyPart(BodyPartType.Foot_L), bodyDamage:getBodyPart(BodyPartType.Foot_R)}
    }
end

ZAV.getRandomScratchAnimation = function()
    return "ZavScratch" .. ZombRand(1, 5);
end

ZAV.handleDamage = function(doInfection)
    local bodyDamage = ZAV.getBodyDamage();

    if not bodyDamage then
        return
    end

    for _, part in pairs(bodyDamage.parts) do
        if part:bitten() then
            part:SetBitten(false);
            part:setBiteTime(0);
            part:setScratched(true, true);
            
            if doInfection then
                ZAV.tryDoPartInfection(part);
            end
        end
    end
end

ZAV.onZombieUpdate = function(zed)
    if zed:isAttacking() and not zed:getModData().attacking then
        if ZombRand(1, 3) == 2 then
            zed:getModData().attacking = true;
            local scratch = ZAV.getRandomScratchAnimation()
            zed:setVariable('AttackType', 'scratch');
            zed:setVariable('isZav', 'true');
            zed:setVariable(scratch, 'true');

            if zed:getTarget() == getPlayer() then
                --fallback remove bites x seconds after
                timer:Simple(5, ZAV.handleDamage);
            end
        end
    end

    if not zed:isAttacking() then
        zed:getModData().attacking = false;
        zed:setVariable('isZav', 'false');
        zed:setVariable('AttackType', 'null');
        zed:setVariable('ZavScratch1', 'false');
        zed:setVariable('ZavScratch2', 'false');
        zed:setVariable('ZavScratch3', 'false');
        zed:setVariable('ZavScratch4', 'false');
    end
end

Events.OnZombieUpdate.Add(ZAV.onZombieUpdate)

local isBite = false;
local function OnPlayerUpdate(player)
    if player == getPlayer() then
        local reaction = player:getHitReaction();
        if reaction == "Bite" and not isBite then
            isBite = true;
        elseif reaction ~= "Bite" and isBite then
            isBite = false;
            ZAV.handleDamage(true);
        end
    end
end

Events.OnPlayerUpdate.Add(OnPlayerUpdate)
